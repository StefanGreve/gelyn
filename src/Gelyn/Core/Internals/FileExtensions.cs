namespace Gelyn.Core.Internals;

/// <summary>
///     The file name extensions the tool works with.
/// </summary>
internal static class FileExtensions
{
    /// <summary>
    ///     The extension of a Markdown file.
    /// </summary>
    internal const string Markdown = ".md";

    /// <summary>
    ///     The extension of a published page.
    /// </summary>
    internal const string Html = ".html";

    /// <summary>
    ///     The extension of a stylesheet.
    /// </summary>
    internal const string Stylesheet = ".css";

    /// <summary>
    ///     The extension of a script.
    /// </summary>
    internal const string Script = ".js";

    /// <summary>
    ///     The extension of an icon.
    /// </summary>
    internal const string Favicon = ".ico";
}
